import type { PrismaTransactionClient } from "../db/types";

/**
 * The nine logical RFID stations matching the WearTrail database schema.
 */
export type RfidStationCode =
  | "fabric_receiving"
  | "fabric_issue"
  | "cutting"
  | "stitching"
  | "finishing"
  | "final_qc"
  | "packing"
  | "warehouse"
  | "dispatch";

/**
 * Normalized uppercase hexadecimal RFID tag UID (typically 4, 7, or 10 bytes).
 */
export type NormalizedTagUid = string;

/**
 * Normalizes a raw RFID UID string by stripping delimiters, spaces, and colons,
 * and converting to uppercase hex.
 */
export function normalizeTagUid(rawUid: string): NormalizedTagUid {
  return rawUid.replace(/[\s:-]/g, "").toUpperCase();
}

/**
 * Versioned Scan Envelope contract (v1).
 * Emitted by the USB Serial Bridge / Controller and delivered to the Express REST endpoint.
 */
export interface VersionedScanEnvelope {
  readonly version: "v1";
  /** Authenticated hardware device identity (UUID) */
  readonly deviceId: string;
  /** Stable unique scan identifier generated by hardware/bridge (UUID) */
  readonly scanId: string;
  /** Boot identifier generated when the ESP32 firmware initializes (UUID) */
  readonly bootId: string;
  /** Monotonically increasing sequence number reset on firmware boot */
  readonly sequence: number;
  /** Hardware antenna/reader index (0..8 for 9-reader prototype) */
  readonly readerIndex: number;
  /** Device reader mapping configuration version */
  readonly mappingVersion: number;
  /** Normalized tag UID */
  readonly tagUid: NormalizedTagUid;
  /** Optional action context ID echoed from station display/selection */
  readonly actionContextId?: string | null;
  /** Hardware device uptime in milliseconds */
  readonly deviceUptimeMs?: number | null;
  /** Scan timestamp in ISO 8601 format */
  readonly timestamp: string;
}

