/**
 * Scan outcome classification.
 */
export type ScanOutcome = "accepted" | "rejected" | "ignored" | "context_required";

/**
 * Structured scan outcome result returned from domain processing.
 */
export interface ScanOutcomeResult {
  readonly scanId: string;
  readonly outcome: ScanOutcome;
  readonly outcomeCode: string;
  readonly outcomeMessage?: string;
  readonly stationCode: RfidStationCode;
  readonly subjectKind?: "material_lot" | "garment";
  readonly subjectId?: string;
  readonly subjectCode?: string;
  readonly processedAt: string;
  readonly nextExpectedStation?: RfidStationCode;
}

/**
 * Subject prepared during Phase 1 of scan handling.
 * Resolves insertion order dependencies between garments, bindings, and scans.
 */
export interface PreparedScanSubject {
  readonly kind: "garment" | "material_lot";
  /** Subject UUID in PostgreSQL */
  readonly subjectId: string;
  /** Human-readable business code (e.g. 'GAR-001' or 'LOT-2026-001') */
  readonly subjectCode: string;
  /** True if this scan is enrolling a newly created entity (e.g. Cutting station) */
  readonly isNewEnrollment: boolean;
  /** Tag UID bound to this subject */
  readonly tagUid: NormalizedTagUid;
  /** Optional metadata passed to Phase 2 */
  readonly metadata?: Record<string, unknown>;
}

/**
 * Domain Scan Handler Contract.
 * Implemented by domain owners (Member 2 for Cutting/Routine, Member 3 for QA/Logistics).
 *
 * Two-phase processing guarantees correct database foreign-key insertion order:
 * - Phase 1 (`prepare`): Prepares/creates the subject entity (e.g., inserts `garments` row first for Cutting enrollment,
 *   or validates existing garment row for QA inspection) before scan record insertion.
 * - Phase 2 (`process`): Executes station-specific mutations, stage transitions, and quality records.
 */
export interface DomainScanHandler<TResult = ScanOutcomeResult> {
  readonly stationCode: RfidStationCode;

  /**
   * Phase 1: Validates prerequisites, resolves context, and prepares/creates the entity
   * within the caller's transaction so database foreign keys are satisfied.
   */
  prepare(
    envelope: VersionedScanEnvelope,
    tx: PrismaTransactionClient,
  ): Promise<PreparedScanSubject>;

  /**
   * Phase 2: Executes business logic (stage transitions, inspections, stock movements)
   * within the same atomic transaction.
   */
  process(
    envelope: VersionedScanEnvelope,
    subject: PreparedScanSubject,
    tx: PrismaTransactionClient,
  ): Promise<TResult>;
}

/**
 * Scan router service contract.
 * Dispatches incoming scan envelopes to the appropriate registered DomainScanHandler.
 */
export interface IScanRoutingService {
  registerHandler(handler: DomainScanHandler): void;
  getHandler(stationCode: RfidStationCode): DomainScanHandler | undefined;
  routeScan(
    envelope: VersionedScanEnvelope,
    tx: PrismaTransactionClient,
  ): Promise<ScanOutcomeResult>;
}
